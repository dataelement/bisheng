@router.post("/gen_title")
async def gen_title(conversationId: str = Body(..., embed=True), login_user=LoginUserDep):
    # The title is generated by a background task kicked off when the chat round
    # ends, so it isn't ready the instant the frontend polls. Wait until a real
    # name lands (slow models take well over the old fixed 5s) instead of racing
    # it — poll the session name up to a deadline, returning as soon as it's set.
    deadline_s = 30.0
    interval_s = 0.5
    waited = 0.0
    name = None
    while waited < deadline_s:
        session = await MessageSessionDao.async_get_one(conversationId)
        name = session.name if session else None
        if name and name != "New Chat":
            break
        await asyncio.sleep(interval_s)
        waited += interval_s
    return resp_200(data={"title": name or "New Chat"})


@router.get("/messages/{conversationId}")
async def get_chat_history(
    conversationId: str,
    login_user=LoginUserDep,
    share_link: Union[ShareLink, None] = ShareLinkDep,
):
    with bypass_tenant_filter_if(share_link is not None):
        messages = await ChatMessageDao.aget_messages_by_chat_id(chat_id=conversationId, limit=1000)
    if not messages:
        return resp_200([])
    if login_user.user_id != messages[0].user_id:
        if not share_link or share_link.resource_id != conversationId:
            return UnAuthorizedError.return_resp()
    return resp_200([await WorkstationMessage.from_chat_message(message) for message in messages])


@router.get("/messages/{conversationId}/agent")
async def get_agent_chat_history(
    conversationId: str,
    login_user=LoginUserDep,
    share_link: Union[ShareLink, None] = ShareLinkDep,
):
    """v2.5: return chat history in the new ChatResponse (Agent-mode) shape.

    - Legacy regenerate sibling branches are collapsed: only the latest
      `create_time` answer per `parentMessageId` survives (R10 / A2).
    - Legacy plain-text answers are converted on-the-fly to JSON shape
      (thinking / web tool_calls extracted from `:::` markers).
    - New Agent-mode messages pass through.
    """
    with bypass_tenant_filter_if(share_link is not None):
        messages = await ChatMessageDao.aget_messages_by_chat_id(chat_id=conversationId, limit=1000)
    if not messages:
        return resp_200([])
    if login_user.user_id != messages[0].user_id:
        if not share_link or share_link.resource_id != conversationId:
            return UnAuthorizedError.return_resp()

    # 1. Drop legacy sibling branches (keep only latest per parentMessageId)
    messages = _drop_legacy_sibling_branches(messages)

    # 2. Map each row through the appropriate formatter
    result = []
    for msg in messages:
        if _is_new_format(msg):
            result.append(_format_new_message(msg))
        else:
            result.append(_convert_legacy_message(msg))
    return resp_200(result)


@router.post("/chat/completions")
@business_activity()
async def chat_completions(
    request: Request,
    data: APIChatCompletion,
    login_user=LoginUserDep,
):
    async def memory_register(chat_id: str) -> None:
        # F132 decision 6: only this login-state endpoint registers a conversation
        # for long-term memory; the open-API entry shares the service function
        # but passes no register callable (AC-10).
        await MemoryGate.open(chat_id, login_user)

    return await stream_chat_completion(request, data, login_user, memory_register=memory_register)


@router.get("/conversations/{conversation_id}/events")
async def conversation_events(
    conversation_id: str,
    last_event_id: str | None = Header(default=None, alias="Last-Event-ID"),
    login_user=LoginUserDep,
):
    """F004: SSE of the conversation's run events (design 决策 4, §4.3).

    Owner only. ``Last-Event-ID`` continues after that event; without it the
    events of the current run are sent from its start. The stream ends when the
    conversation has no run in progress.
    """
    if not await run_send.owns_conversation(conversation_id, login_user):
        # Same answer for "not yours" and "does not exist".
        return UnAuthorizedError.return_resp()
    return await run_send.subscribe_response(conversation_id, last_event_id)


@router.get("/conversations/{conversation_id}/files/{file_id}/url")
async def conversation_file_url(conversation_id: str, file_id: str, login_user=LoginUserDep):
    """F004 (AC-24, AC-28): fresh link to a file of the conversation. Owner only.

    Covers a file the current run announced with a ``file`` event before any
    message row carries it; other files are answered from the stored rows.
    """
    from ...domain.services import run_files

    if not await run_send.owns_conversation(conversation_id, login_user):
        return UnAuthorizedError.return_resp()
    return resp_200(data={"url": await run_files.resolve_run_file_url(conversation_id, file_id, login_user)})


@router.post("/conversations/{conversation_id}/stop")
async def stop_conversation(conversation_id: str, login_user=LoginUserDep):
    """F004: stop the run that holds the conversation (AC-29). Owner only.

    Works for a direct answer and for deep research, on any node. Returns
    ``{run_id, status}``: ``stopping`` (the run ends within about a second and
    writes ``run_stopped``), ``stopped`` (it was waiting for an answer or still
    queued and is ended now), ``expired`` or ``idle`` (nothing to stop).
    """
    if not await run_send.owns_conversation(conversation_id, login_user):
        return UnAuthorizedError.return_resp()
    return resp_200(data=await run_send.stop_conversation_run(conversation_id))
