import React from 'react';
import { fireEvent, render, screen } from '@testing-library/react';
import { normalizeApiError } from '@bisheng/api-client';
import Nav from './Nav';
const mockRetry = jest.fn(async () => ({}));
const mockQuery = { data: undefined, error: undefined, isError: false, isSuccess: false, refetch: mockRetry, fetchNextPage: mockRetry };
const mockSearch = { pageNumber: 1, searchQuery: '', setPageNumber: jest.fn(), searchQueryRes: { data: { pages: [{ conversations: [{ title: 'Search result' }] }] } } };
const localize = (key: string) => key;
jest.mock('~/hooks/queries/data-provider', () => ({ useConversationsInfiniteQuery: () => mockQuery }));
jest.mock('~/Providers', () => ({ useSearchContext: () => mockSearch }));
jest.mock('~/hooks', () => ({ useLocalize: () => localize, useAuthContext: () => ({ isAuthenticated: true }), useHasAccess: () => false, useLocalStorage: () => [false, jest.fn()], usePrefersMobileLayout: () => true, useNavScrolling: () => ({ containerRef: { current: null }, moveToTop: jest.fn() }) }));
jest.mock('~/api/request', () => ({ showApiError: jest.fn() }));
jest.mock('~/utils', () => ({ cn: (...v: unknown[]) => v.filter(Boolean).join(' ') }));
jest.mock('~/components/Conversations', () => ({ Conversations: ({ conversations }: { conversations: { title: string }[] }) => <>{conversations.map(c => <div key={c.title}>{c.title}</div>)}</> }));
jest.mock('./NewChat', () => () => null);
jest.mock('./NavToggle', () => () => null);
jest.mock('./ChatNavUserFooter', () => ({ ChatNavUserFooter: () => null }));
jest.mock('./AccountSettings', () => () => null);
beforeEach(() => { Object.assign(mockQuery, { data: undefined, error: undefined, isError: false, isSuccess: false }); mockSearch.searchQuery = ''; });
it('renders persistent history failure and retry without pretending history is empty', async () => {
  Object.assign(mockQuery, { error: normalizeApiError({ status_code: 19004 }, { message: 'History unavailable' }), isError: true });
  render(<Nav navVisible setNavVisible={jest.fn()} />);
  expect(screen.getByText('History unavailable')).toBeInTheDocument();
  expect(screen.queryByText('com_app_chat_sidebar_empty')).not.toBeInTheDocument();
  mockRetry.mockClear();
  fireEvent.click(screen.getByText('com_ui_retry'));
  await Promise.resolve();
  expect(mockRetry).toHaveBeenCalled();
});
it('distinguishes successful empty history and preserves search results when the normal history failed', () => {
  mockQuery.isSuccess = true;
  const { rerender } = render(<Nav navVisible setNavVisible={jest.fn()} />);
  expect(screen.getByText('com_app_chat_sidebar_empty')).toBeInTheDocument();
  mockSearch.searchQuery = 'result';
  Object.assign(mockQuery, { error: new Error('History unavailable'), isError: true });
  rerender(<Nav navVisible setNavVisible={jest.fn()} />);
  expect(screen.getByText('Search result')).toBeInTheDocument();
  expect(screen.queryByText('History unavailable')).not.toBeInTheDocument();
});
