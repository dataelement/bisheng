"""MCP-local orchestration for server-side knowledge-space answering.

Mirrors ``POST /api/v2/filelib/answer`` without calling the FastAPI endpoint
function. The answer is generated by a model configured on the server side, so
the caller does not need to know a model id: it falls back to
``open_mcp.answer_default_model_id``.
"""

from __future__ import annotations

from fastapi import HTTPException

from bisheng.common.errcode.open_api import OpenApiAuthDependencyUnavailableError
from bisheng.common.errcode.permission import PermissionServiceUnavailableError
from bisheng.common.errcode.tenant_fga import PermissionBackendUnavailableError
from bisheng.common.services.config_service import settings
from bisheng.core.database import get_async_db_session
from bisheng.knowledge.domain.repositories.implementations.knowledge_document_version_repository_impl import (
    KnowledgeDocumentVersionRepositoryImpl,
)
from bisheng.knowledge.domain.repositories.implementations.knowledge_repository_impl import KnowledgeRepositoryImpl
from bisheng.knowledge.domain.schemas.knowledge_answer_schema import KnowledgeAnswerReq, KnowledgeAnswerResp
from bisheng.knowledge.domain.services.knowledge_space_answer_service import KnowledgeSpaceAnswerService
from bisheng.knowledge.domain.services.knowledge_space_chat_service import KnowledgeSpaceChatService
from bisheng.open_endpoints.domain.utils import get_open_api_operator_async
from bisheng.open_mcp.application import current_request


def resolve_model_id(requested: int | None) -> int:
    model_id = requested or settings.open_mcp.answer_default_model_id
    if not model_id:
        raise HTTPException(
            status_code=400,
            detail="model_id is required: pass it, or configure open_mcp.answer_default_model_id",
        )
    return model_id


async def answer_knowledge(*, command) -> KnowledgeAnswerResp:
    payload = command.model_dump(exclude_none=True)
    payload["model_id"] = resolve_model_id(command.model_id)
    request_data = KnowledgeAnswerReq.model_validate(payload)
    login_user = await get_open_api_operator_async()
    async with get_async_db_session() as session:
        retrieval = KnowledgeSpaceChatService(request=current_request(), login_user=login_user)
        retrieval.version_repo = KnowledgeDocumentVersionRepositoryImpl(session)
        service = KnowledgeSpaceAnswerService(
            login_user=login_user,
            knowledge_repository=KnowledgeRepositoryImpl(session),
            retrieval_service=retrieval,
        )
        try:
            return await service.answer(request_data)
        except (PermissionBackendUnavailableError, PermissionServiceUnavailableError) as exc:
            raise OpenApiAuthDependencyUnavailableError() from exc


__all__ = ["answer_knowledge", "resolve_model_id"]
