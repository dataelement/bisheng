import React from 'react';
import { MemoryRouter } from 'react-router-dom';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { normalizeApiError } from '@bisheng/api-client';
import { getArticlesApi } from '~/api/channels';
import { ArticleList } from './ArticleList';
const localize = (key: string) => key;
const detail = { source_infos: [], filter_rules: [] };
const mockSetMobile = jest.fn();
jest.mock('~/hooks', () => ({ useLocalize: () => localize, usePrefersMobileLayout: () => false, useWorkbenchMenuNames: () => ({ channel: 'Subscription' }), useDebounce: (v: unknown) => v }));
jest.mock('~/Providers', () => ({ useToastContext: () => ({ showToast: jest.fn() }) }));
jest.mock('recoil', () => ({ atom: () => ({}), useSetRecoilState: () => mockSetMobile }));
jest.mock('@tanstack/react-query', () => ({ useQuery: () => ({ data: detail, isLoading: false }), useQueryClient: () => ({}) }));
jest.mock('~/api/request', () => ({ showApiError: jest.fn() }));
jest.mock('~/api/channels', () => ({ getArticlesApi: jest.fn() }));
jest.mock('~/components/CopyShareLinkButton', () => ({ CopyShareLinkButton: () => null }));
jest.mock('~/components/illustrations', () => ({ EmptyStateIllustration: () => null }));
jest.mock('~/utils', () => ({ cn: (...parts: unknown[]) => parts.filter(Boolean).join(' ') }));
jest.mock('./ArticleCard', () => ({ ArticleCard: ({ article }: { article: { title: string } }) => <div>{article.title}</div> }));
jest.mock('./ChannelActionsMenu', () => ({ ChannelActionsMenu: () => null }));
jest.mock('./ChannelSwitcher', () => ({ ChannelSwitcher: () => null, SERIF_FONT_STACK: '' }));
jest.mock('./MultiSourceSelect', () => ({ MultiSourceSelect: () => null }));
jest.mock('./SearchInput', () => ({ SearchInput: ({ onChange }: { onChange: (value: string) => void }) => <button onClick={() => onChange('filter')}>filter</button> }));
jest.mock('~/components/InfiniteScroll', () => ({ InfiniteScroll: ({ children, loadMore, hasMore }: { children: React.ReactNode; loadMore: () => unknown; hasMore: boolean }) => <>{children}{hasMore && <button onClick={loadMore}>more</button>}</> }));
const channel = { id: 'channel', name: 'Channel' } as Parameters<typeof ArticleList>[0]['channel'];
const error = normalizeApiError({ status_code: 19004, data: { page: 'unavailable' } }, { message: 'Articles unavailable' });
const first = { data: [{ doc_id: 'first', title: 'First article' }], total: 40 };
beforeEach(() => { (getArticlesApi as jest.Mock).mockReset(); });
it('shows first-page failure instead of no content and retry can display a successful empty list', async () => {
  (getArticlesApi as jest.Mock).mockRejectedValueOnce(error).mockResolvedValue({ data: [], total: 0 });
  render(<MemoryRouter><ArticleList channel={channel} onArticleSelect={jest.fn()} /></MemoryRouter>);
  expect(await screen.findByText('Articles unavailable')).toBeInTheDocument();
  expect(screen.queryByText('com_subscription.no_related_content')).not.toBeInTheDocument();
  fireEvent.click(screen.getByText('com_ui_retry'));
  expect(await screen.findByText('com_subscription.no_related_content')).toBeInTheDocument();
});
it('keeps existing articles on failed reload and failed pagination; retry continues the failed page', async () => {
  (getArticlesApi as jest.Mock).mockResolvedValueOnce(first).mockRejectedValue(error);
  render(<MemoryRouter><ArticleList channel={channel} onArticleSelect={jest.fn()} /></MemoryRouter>);
  expect(await screen.findByText('First article')).toBeInTheDocument();
  fireEvent.click(screen.getByText('filter'));
  expect(await screen.findByText('Articles unavailable')).toBeInTheDocument();
  expect(screen.getByText('First article')).toBeInTheDocument();
  (getArticlesApi as jest.Mock).mockResolvedValueOnce(first);
  fireEvent.click(screen.getByText('com_ui_retry'));
  await waitFor(() => expect(screen.queryByText('Articles unavailable')).not.toBeInTheDocument());
  fireEvent.click(screen.getByText('more'));
  expect(await screen.findByText('Articles unavailable')).toBeInTheDocument();
  expect(screen.getByText('First article')).toBeInTheDocument();
  (getArticlesApi as jest.Mock).mockResolvedValueOnce({ data: [{ doc_id: 'second', title: 'Second article' }], total: 40 });
  await act(async () => fireEvent.click(screen.getByText('com_ui_retry')));
  expect(await screen.findByText('Second article')).toBeInTheDocument();
  expect(screen.getByText('First article')).toBeInTheDocument();
  expect(screen.queryByText('Articles unavailable')).not.toBeInTheDocument();
});
