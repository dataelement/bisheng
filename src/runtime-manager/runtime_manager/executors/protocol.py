"""Execution capabilities independent of a particular container engine."""

from typing import Protocol


class ExecutorError(RuntimeError):
    """A safe execution reason; application output is an explicit separate field."""

    def __init__(self, reason: str, *, tail: str = ""):
        super().__init__(reason)
        self.tail = tail


class RuntimeExecutor(Protocol):
    def capabilities(self) -> dict: ...
    def prepare(self, operation: dict) -> dict: ...
    def launch(self, operation: dict, *, preview: bool = False) -> dict: ...
    def observe(self, exec_ref: str) -> dict: ...
    def request_stop(self, exec_ref: str, operation: dict) -> dict: ...
    def confirm_stopped(self, exec_ref: str) -> dict: ...
    def cleanup(self, operation: dict) -> dict: ...
    def logs(self, exec_ref: str, *, since=None, tail: int = 200) -> str: ...
    def data(self, operation: dict, action: str, parameters: dict) -> dict: ...
