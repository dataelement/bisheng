def orders(root, as_of=None):
    base = as_of or datetime.now(ZoneInfo("Asia/Shanghai")).date()
    result = {"asOf": base.isoformat(), "orders": [], "initialReminders": {}}

    def day(offset):
        return None if offset is None else (base + timedelta(days=offset)).isoformat()

    for i, offset in enumerate((3, -6, None), 1):
        due_date = day(offset)
        result["orders"].append(
            {
                "id": "SIM-ORDER-" + str(i),
                "number": "DEMO-ORDER-" + str(i).zfill(3),
                "supplier": "合成订单供应商" + str(i),
                "customer": "演示客户甲",
                "mock": True,
                "amount": 1000 * i,
                "currency": "CNY",
                "lines": [
                    {
                        "id": "SIM-OL-" + str(i),
                        "line": 1,
                        "part": "DEMO-QPL-001",
                        "code": "SIM-OMAT",
                        "material": "合成铝合金材料",
                        "quantity": 10,
                        "unit": "件",
                        "price": 100 * i,
                        "amount": 1000 * i,
                        "due": due_date,
                    }
                ],
                "invoices": [
                    {
                        "id": "SIM-OI-" + str(i),
                        "number": "SIM-INV-" + str(i),
                        "due": due_date,
                        "invoiceAmount": 1000 * i,
                    }
                ],
                "settlements": [
                    {
                        "id": "SIM-OS-" + str(i),
                        "number": "SIM-SET-" + str(i),
                        "date": due_date,
                        "amount": 1000 * i,
                    }
                ],
            }
        )
    # Keep most examples upcoming while exercising past, due today, and missing dates.
    offsets = (12, 17, 9, 0, 2, 3, 7, 8, 15, 30, 31, 60, None)

    for i in range(4, 25):
        offset = offsets[(i - 4) % len(offsets)]
        lines = []
        for line in range(1, 3 if i % 3 == 0 else 2):
            quantity, price = i + line, 40 + i * 5 + line
            lines.append(
                {
                    "id": f"SIM-OL-{i}-{line}",
                    "line": line,
                    "part": ("26DMAC", "ZDA601US", "SIM-BUSH-003", "SIM-SEAL-004")[
                        (i + line) % 4
                    ],
                    "code": f"SIM-OMAT-{i}-{line}",
                    "material": ("合成连接件", "合成密封件", "合成衬套", "合成紧固件")[
                        (i + line) % 4
                    ],
                    "quantity": quantity,
                    "unit": "件",
                    "price": price,
                    "amount": quantity * price,
                    "due": day(None if offset is None else offset + (line - 1) * 4),
                }
            )
        amount = sum(line["amount"] for line in lines)
        # Some orders have multiple invoices/settlements with distinct dates;
        # missing dates are explicit and must never become overdue dates.
        count = 2 if i % 4 == 0 else 1
        invoices, settlements = [], []
        for j in range(1, count + 1):
            invoices.append(
                {
                    "id": f"SIM-OI-{i}-{j}",
                    "number": f"SIM-INV-{i}-{j}",
                    "due": day(None if offset is None else offset - 2 + (j - 1) * 9),
                    "invoiceAmount": amount / count,
                }
            )
            settlements.append(
                {
                    "id": f"SIM-OS-{i}-{j}",
                    "number": f"SIM-SET-{i}-{j}",
                    "date": day(None if offset is None else offset + 5 + (j - 1) * 11),
                    "amount": amount / count,
                }
            )
        result["orders"].append(
            {
                "id": f"SIM-ORDER-{i}",
                "number": f"DEMO-ORDER-{i:03d}",
                "supplier": f"合成订单供应商{(i - 1) % 4 + 1}",
                "customer": "演示客户甲" if i % 2 else "演示客户乙",
                "mock": True,
                "amount": amount,
                "currency": "CNY",
                "lines": lines,
                "invoices": invoices,
                "settlements": settlements,
            }
        )
    write(root, "skills/order-tracking/assets/orders.json", result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime", required=True)
    parser.add_argument("--platform-base", default="http://frontend:3001")
    args = parser.parse_args()
    root = Path(args.runtime).expanduser().resolve()
    repo = ROOT.parents[1]
    if root.exists() or root == repo or repo in root.parents:
        raise SystemExit("Use a NEW destination outside the source repository")
    root.mkdir(parents=True, mode=0o700)
    shutil.copytree(
        ROOT / "skills",
        root / "skills",
        ignore=shutil.ignore_patterns("__pycache__", "assets"),
    )
    shutil.copytree(
        ROOT / "forecast",
        root / "forecast",
        ignore=shutil.ignore_patterns(
            "__pycache__", "runtime*", "assets", "*.sqlite*", "*.db"
        ),
    )
    procurement(root)
    transport(root)
    customs(root)
    orders(root)
    runpy.run_path(str(root / "forecast/seed_fixtures.py"), run_name="__main__")
    credentials = {key: secrets.token_hex(24) for key in ("appKey", "appSecret")}
    transport_token, customs_token, orders_key = (
        secrets.token_hex(24) for _ in range(3)
    )
    write(root, "procurement/credentials.json", credentials, private=True)
    write(
        root,
        "private/procurement/client.json",
        {
            "base_url": "http://procurement-api:18768",
            "functionCode": "mock_procurement_history_v1",
            **credentials,
        },
        private=True,
    )
    for scene, token in (("transport", transport_token), ("customs", customs_token)):
        write(
            root,
            f"private/{scene}/client.json",
            {"base_url": f"http://bs-d-{scene}-api:8080", "token": token},
            private=True,
        )
        write(
            root, f"{scene}.env", f"{scene.upper()}_MOCK_TOKEN={token}\n", private=True
        )
    write(
        root,
        "transport-native.env",
        f"TRANSPORT_MOCK_TOKEN={transport_token}\nTRANSPORT_API_ORIGIN=http://bs-d-transport-api:8080\n",
        private=True,
    )
    write(root, "orders.env", f"ZHGYL_ORDERS_DATA_KEY={orders_key}\n", private=True)
    write(
        root,
        "forecast.env",
        f"FORECAST_PLATFORM_BASE={args.platform_base}\nFORECAST_AGENT_BASE_URL=http://procurement-forecast:8786\nFORECAST_NATIVE_TOOL_KEY=\nFORECAST_NATIVE_MODEL_ID=\n",
        private=True,
    )
    write(
        root,
        "orders-nginx.conf",
        'location = /api/zhgyl/orders {\n    proxy_pass http://orders-data:8080/api/zhgyl/orders;\n    proxy_set_header X-Zhgyl-Data-Key "'
        + orders_key
        + '";\n    add_header Cache-Control "no-store" always;\n}\n',
        private=True,
    )
    (root / "transport-state").mkdir(mode=0o700)
    (root / "forecast-runtime").mkdir(mode=0o700)
    bundles = root / "skill-bundles"
    bundles.mkdir(mode=0o700)
    manifests = []
    for skill in [
        *sorted((root / "skills").iterdir()),
        root / "forecast/skill/procurement-forecast-fast",
    ]:
        if not skill.is_dir():
            continue
        package = bundles / (skill.name + ".zip")
        files = []
        with zipfile.ZipFile(package, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(skill.rglob("*")):
                if path.is_file() and "__pycache__" not in path.parts:
                    relative = path.relative_to(skill).as_posix()
                    archive.write(path, relative)
                    files.append(
                        {
                            "path": relative,
                            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                        }
                    )
        manifests.append(
            {
                "name": skill.name,
                "package_sha256": hashlib.sha256(package.read_bytes()).hexdigest(),
                "files": files,
            }
        )
    write(
        root,
        "skill-bundles/manifest.json",
        {"synthetic_assets": True, "skills": manifests},
    )
    # Rebuildable local-only token cache must be writable by the worker owner.
    print(
        json.dumps(
            {
                "runtime": str(root),
                "synthetic_only": True,
                "procurement_rows": 6,
                "transport_details": len(
                    json.loads((root / "transport/snapshot.json").read_text())[
                        "details"
                    ]
                ),
                "customs_details": len(
                    json.loads((root / "customs/snapshot.json").read_text())["details"]
                ),
                "orders": len(
                    json.loads(
                        (root / "skills/order-tracking/assets/orders.json").read_text()
                    )["orders"]
                ),
                "private_values_printed": False,
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
