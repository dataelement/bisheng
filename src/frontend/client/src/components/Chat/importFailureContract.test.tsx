describe.each(['daily', 'app'])('%s import UI endpoint', surface => {
  const mount = () => {
    render(surface === 'daily' ? <DailyChatView /> : <AppChatView data={{ id: 'flow', name: 'App', flow_type: 5 }} cid="chat" v="v1" readOnly={false} />);
    fireEvent.click(screen.getByText('open import'));
  };
  it.each(['business', 'global', 'canceled'])('retains %s evidence and leaves the picker open without a second toast', async kind => {
    const error = normalizeApiError(kind === 'canceled' ? { code: 'ERR_CANCELED' } : { status_code: 12067, data: { space: 9 } }, { message: 'Import unavailable' });
    if (kind === 'global') error.presentation = 'global';
    (importMessagesToKnowledgeApi as jest.Mock).mockRejectedValueOnce(error);
    mount();
    fireEvent.click(screen.getByText('confirm import'));
    await waitFor(() => expect(showApiError).toHaveBeenCalledWith(error));
    expect(mockToast).not.toHaveBeenCalled();
    expect(mockExit).not.toHaveBeenCalled();
    expect(screen.getByText('confirm import')).toBeInTheDocument();
  });
  it('keeps the original local fallback and only closes after an actual successful import', async () => {
    (importMessagesToKnowledgeApi as jest.Mock).mockRejectedValueOnce(new Error('local failure')).mockResolvedValueOnce({ target_filename: 'chat.docx' });
    mount();
    fireEvent.click(screen.getByText('confirm import'));
    await waitFor(() => expect(mockToast).toHaveBeenCalledWith(expect.objectContaining({ message: 'workstation.messageExport.renderFailed' })));
    expect(mockExit).not.toHaveBeenCalled();
    fireEvent.click(screen.getByText('confirm import'));
    await waitFor(() => expect(screen.queryByText('confirm import')).not.toBeInTheDocument());
    expect(mockExit).toHaveBeenCalledTimes(1);
  });
});
